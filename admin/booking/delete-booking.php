<?php
/**
 * Booking Module - Delete Action Handler
 *
 * Path: admin/booking/delete-booking.php
 *
 * @package NahianMovieBookingPlugin
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

$admin_cap = defined( 'NMBP_ADMIN_CAP' ) ? NMBP_ADMIN_CAP : 'manage_options';
if ( ! current_user_can( $admin_cap ) ) {
	wp_die( esc_html__( 'Unauthorized access.', 'nahian-movie-booking-plugin' ), 403 );
}

global $wpdb;
$table_bookings = $wpdb->prefix . 'nmbp_bookings';
$del_id         = isset( $_GET['id'] ) ? absint( $_GET['id'] ) : 0;

if ( $del_id <= 0 ) {
	wp_die(
		esc_html__( 'Invalid booking identifier.', 'nahian-movie-booking-plugin' ),
		esc_html__( 'Error', 'nahian-movie-booking-plugin' ),
		array( 'response' => 400 )
	);
}

// Default nonce query arg generated by wp_nonce_url() is '_wpnonce'.
check_admin_referer( 'nmbp_delete_booking_' . $del_id, '_wpnonce' );

$deleted      = $wpdb->delete(
	$table_bookings,
	array( 'id' => $del_id ),
	array( '%d' )
);
$redirect_arg = ( false !== $deleted && 0 !== $deleted ) ? 'booking_deleted=true' : 'booking_error=db_failed';

wp_safe_redirect( admin_url( 'admin.php?page=nmbp-booking&subtab=all&' . $redirect_arg ) );
exit;