<?php
/**
 * Booking Module - Delete Action Handler
 *
 * Path: admin/booking/delete-booking.php
 *
 * @package BigScreenCinemas
 */

if ( ! defined( 'ABSPATH' ) ) {
    exit;
}

$admin_cap = defined( 'BSC_ADMIN_CAP' ) ? BSC_ADMIN_CAP : 'manage_options';
if ( ! current_user_can( $admin_cap ) ) {
    wp_die( esc_html__( 'Unauthorized access.', 'bcs-screen-manager' ), 403 );
}

global $wpdb;
$table_bookings = $wpdb->prefix . 'bsc_bookings';
$del_id         = isset( $_GET['id'] ) ? absint( $_GET['id'] ) : 0;

if ( $del_id <= 0 ) {
    wp_die(
        esc_html__( 'Invalid booking identifier.', 'bcs-screen-manager' ),
        esc_html__( 'Error', 'bcs-screen-manager' ),
        array( 'response' => 400 )
    );
}

// Default nonce query arg generated by wp_nonce_url() is '_wpnonce'
check_admin_referer( 'bsc_delete_booking_' . $del_id, '_wpnonce' );

$deleted = $wpdb->delete(
    $table_bookings,
    array( 'id' => $del_id ),
    array( '%d' )
);

if ( false !== $deleted && 0 !== $deleted ) {
    wp_safe_redirect( admin_url( 'admin.php?page=bsc-booking&subtab=all&booking_deleted=true' ) );
    exit;
} else {
    wp_safe_redirect( admin_url( 'admin.php?page=bsc-booking&subtab=all&booking_error=db_failed' ) );
    exit;
}